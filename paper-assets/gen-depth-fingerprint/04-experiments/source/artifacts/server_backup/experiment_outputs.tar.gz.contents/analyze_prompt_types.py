def downsample(df: pd.DataFrame, rng) -> pd.DataFrame:
    counts = df["label"].value_counts()
    min_n = counts.min()
    parts = [df[df["label"] == lbl].sample(n=min_n, random_state=rng, replace=False)
             for lbl in sorted(counts.index)]
    return pd.concat(parts, ignore_index=True)


def bootstrap_f1(y_true, y_pred, n_boot=1000):
    rng = np.random.RandomState(SEED)
    n = len(y_true)
    scores = []
    for _ in range(n_boot):
        idx = rng.randint(0, n, size=n)
        yt, yp = y_true[idx], y_pred[idx]
        if len(np.unique(yt)) < len(CLASS_NAMES):
            continue
        scores.append(f1_score(yt, yp, average="macro"))
    arr = np.array(scores)
    return dict(mean=float(np.mean(arr)),
                ci_lo=float(np.percentile(arr, 2.5)),
                ci_hi=float(np.percentile(arr, 97.5)))


def train_eval_classifier(train_df, test_df) -> dict:
    rng = np.random.RandomState(SEED)
    train_ds = downsample(train_df, rng)
    X_train, y_train = train_ds[FEATURES].values, train_ds["label"].values
    X_test, y_test = test_df[FEATURES].values, test_df["label"].values

    clf = XGBClassifier(**XGB_PARAMS)
    clf.fit(X_train, y_train)
    y_pred = clf.predict(X_test)

    macro_f1 = float(f1_score(y_test, y_pred, average="macro"))
    per_class = f1_score(y_test, y_pred, average=None, labels=[0, 1, 2])
    boot = bootstrap_f1(y_test, y_pred)

    return dict(macro_f1=macro_f1,
                per_class={name: float(per_class[i]) for i, name in enumerate(CLASS_NAMES)},
                bootstrap_ci=boot,
                n_train=len(train_ds), n_test=len(test_df))


