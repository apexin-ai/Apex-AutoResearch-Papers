def load_model(device: str):
    print(f"Loading reference model from {MODEL_SNAPSHOT} on {device}")
    tokenizer = AutoTokenizer.from_pretrained(MODEL_SNAPSHOT, local_files_only=True)
    model = AutoModelForCausalLM.from_pretrained(
        MODEL_SNAPSHOT, local_files_only=True, torch_dtype=torch.float16,
    ).to(device).eval()
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    return tokenizer, model


def compute_reference_features(texts: list[str], tokenizer, model,
                                device: str, batch_size: int) -> list[dict]:
    results = []
    for start in range(0, len(texts), batch_size):
        batch_texts = texts[start:start + batch_size]
        encodings = tokenizer(
            batch_texts, return_tensors="pt", padding=True,
            truncation=True, max_length=512,
        ).to(device)

        with torch.no_grad():
            logits = model(**encodings).logits

        for i in range(len(batch_texts)):
            mask = encodings["attention_mask"][i].bool()
            seq_len = mask.sum().item()
            if seq_len < 2:
                results.append(dict(entropy_mean=0., entropy_std=0.,
                                    entropy_min=0., entropy_max=0., tail_decay=0.))
                continue

            token_logits = logits[i, :seq_len - 1, :]
            log_probs = torch.log_softmax(token_logits, dim=-1)
            probs = torch.exp(log_probs)
            entropy = -(probs * log_probs).sum(dim=-1)
            entropy_np = entropy.float().cpu().numpy()

            avg_lp = log_probs.float().mean(dim=0)
            sorted_lp, _ = torch.sort(avg_lp, descending=True)
            sorted_lp_np = sorted_lp.cpu().numpy()

            vocab_size = sorted_lp_np.shape[0]
            hi = min(1000, vocab_size)
            lo = min(100, hi)
            if hi - lo >= 2:
                x = np.arange(lo, hi, dtype=np.float64)
                y = sorted_lp_np[lo:hi].astype(np.float64)
                tail_decay = float(np.polyfit(x, y, 1)[0])
            else:
                tail_decay = 0.0

            results.append(dict(
                entropy_mean=float(np.mean(entropy_np)),
                entropy_std=float(np.std(entropy_np)),
                entropy_min=float(np.min(entropy_np)),
                entropy_max=float(np.max(entropy_np)),
                tail_decay=tail_decay,
            ))

        done = min(start + batch_size, len(texts))
        if done % 500 == 0 or done == len(texts):
            print(f"  Reference features: {done}/{len(texts)}")
    return results


def compute_surface_features(texts: list[str]) -> list[dict]:
    results = []
    for text in texts:
        words = text.lower().split()
        n = len(words)
        if n == 0:
            results.append(dict(ttr=0., hapax_ratio=0.))
            continue
        counter = Counter(words)
        results.append(dict(
            ttr=len(counter) / n,
            hapax_ratio=sum(1 for c in counter.values() if c == 1) / n,
        ))
    return results


def extract_all_features(df: pd.DataFrame, device: str, batch_size: int) -> pd.DataFrame:
    """Extract features for all records, return augmented DataFrame."""
    texts = df["text"].tolist()
    tokenizer, model = load_model(device)
    ref_feats = compute_reference_features(texts, tokenizer, model, device, batch_size)
    del model, tokenizer
    torch.cuda.empty_cache()
    surf_feats = compute_surface_features(texts)

    feat_df = pd.DataFrame([{**r, **s} for r, s in zip(ref_feats, surf_feats)])
    for col in FEATURES:
        df[col] = feat_df[col].values
    return df


