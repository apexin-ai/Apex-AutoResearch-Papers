def main():
    parser = argparse.ArgumentParser(description="Prompt type comparison analysis (plan-005)")
    parser.add_argument("--device", default="cuda:0", help="CUDA device")
    parser.add_argument("--batch-size", type=int, default=8, help="GPU batch size")
    parser.add_argument("--features-csv", default="data/prompt_type_features.csv",
                        help="Path to save/load features CSV")
    parser.add_argument("--output", default="data/prompt_type_results.json",
                        help="Output JSON path")
    parser.add_argument("--skip-extraction", action="store_true",
                        help="Skip feature extraction, load from --features-csv")
    parser.add_argument("--dry-run", action="store_true",
                        help="Process only first 50 records per prompt type")
    args = parser.parse_args()

    features_path = PROJECT_ROOT / args.features_csv
    output_path = PROJECT_ROOT / args.output

    # --- Load data ---
    print("Loading data...")
    df = load_all_data()

    if args.dry_run:
        df = df.groupby("prompt_type").head(50).reset_index(drop=True)
        print(f"[dry-run] Trimmed to {len(df)} records")

    # --- Feature extraction ---
    if args.skip_extraction and features_path.exists():
        print(f"\nLoading pre-extracted features from {features_path}")
        feat_df = pd.read_csv(features_path)
        for col in FEATURES:
            df[col] = feat_df[col].values
    else:
        print(f"\nExtracting features ({len(df)} texts)...")
        df = extract_all_features(df, args.device, args.batch_size)
        features_path.parent.mkdir(parents=True, exist_ok=True)
        df[["id", "depth", "seed_id", "prompt_type"] + FEATURES].to_csv(
            features_path, index=False)
        print(f"Features saved to {features_path}")

    # --- Analysis ---
    all_results = {}

    print("\n" + "=" * 60)
    print("1. Per-Prompt-Type Depth Signal")
    print("=" * 60)
    all_results["per_prompt_type_signal"] = per_prompt_type_depth_signal(df)

    print("\n" + "=" * 60)
    print("2. Leave-One-Prompt-Type-Out (LOPTO)")
    print("=" * 60)
    all_results["leave_one_prompt_type_out"] = leave_one_prompt_type_out(df)

    print("\n" + "=" * 60)
    print("3. Depth Decay Comparison")
    print("=" * 60)
    all_results["depth_decay"] = depth_decay_comparison(df)

    print("\n" + "=" * 60)
    print("4. Feature Distribution Comparison")
    print("=" * 60)
    all_results["feature_distributions"] = feature_distribution_comparison(df)

    # --- Output ---
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(all_results, f, indent=2, ensure_ascii=False)
    print(f"\nResults saved to {output_path}")

    print_summary(all_results)


if __name__ == "__main__":
    main()
