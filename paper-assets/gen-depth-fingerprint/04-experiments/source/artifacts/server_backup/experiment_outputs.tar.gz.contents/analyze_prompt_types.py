def print_summary(results: dict):
    """Print a concise summary table to stdout."""
    print("\n" + "=" * 80)
    print("PROMPT TYPE COMPARISON SUMMARY")
    print("=" * 80)

    # 1. Per-type depth signal
    print("\n1. Per-Prompt-Type Depth Signal (within-type 5-fold CV)")
    print(f"{'Prompt Type':>25s}  {'N':>6s}  {'CV5 F1':>8s}  {'±std':>6s}")
    print("-" * 55)
    sig = results.get("per_prompt_type_signal", {})
    for pt in PROMPT_TYPES:
        r = sig.get(pt, {})
        if "cv5_macro_f1" in r:
            cv = r["cv5_macro_f1"]
            print(f"{pt:>25s}  {r['n']:6d}  {cv['mean']:8.4f}  {cv['std']:6.4f}")
        else:
            print(f"{pt:>25s}  {'N/A':>6s}  {'N/A':>8s}  {'N/A':>6s}")

    # 2. LOPTO
    print("\n2. Leave-One-Prompt-Type-Out (LOPTO)")
    print(f"{'Hold-out':>25s}  {'F1':>8s}  {'95% CI':>20s}  {'n_test':>7s}")
    print("-" * 65)
    lopto = results.get("leave_one_prompt_type_out", {})
    for pt in PROMPT_TYPES:
        r = lopto.get(pt, {})
        if "macro_f1" in r:
            ci = r["bootstrap_ci"]
            print(f"{pt:>25s}  {r['macro_f1']:8.4f}  "
                  f"[{ci['ci_lo']:.4f}, {ci['ci_hi']:.4f}]  {r['n_test']:7d}")
    if "average_macro_f1" in lopto:
        print(f"{'AVERAGE':>25s}  {lopto['average_macro_f1']:8.4f}")

    # 3. Depth decay slopes
    print("\n3. Depth Decay Slopes (linear fit of feature mean vs depth)")
    decay = results.get("depth_decay", {})
    header_feats = ["entropy_mean", "entropy_std", "tail_decay", "ttr"]
    print(f"{'Prompt Type':>25s}  " + "  ".join(f"{f:>14s}" for f in header_feats))
    print("-" * (25 + 2 + len(header_feats) * 16))
    for pt in PROMPT_TYPES:
        r = decay.get(pt, {})
        if isinstance(r, dict) and "status" not in r:
            vals = [f"{r[f]['linear_slope']:+14.6f}" for f in header_feats]
            print(f"{pt:>25s}  " + "  ".join(vals))

    # 4. Top Spearman correlations
    print("\n4. Strongest Depth Correlations per Prompt Type (|ρ| top-3)")
    for pt in PROMPT_TYPES:
        r = sig.get(pt, {})
        if "spearman_correlations" not in r:
            continue
        corrs = r["spearman_correlations"]
        sorted_feats = sorted(corrs.items(), key=lambda x: abs(x[1]["rho"]), reverse=True)[:3]
        top_str = ", ".join(f"{f}={v['rho']:+.4f}" for f, v in sorted_feats)
        print(f"  {pt:25s}: {top_str}")

    print("\n" + "=" * 80)


