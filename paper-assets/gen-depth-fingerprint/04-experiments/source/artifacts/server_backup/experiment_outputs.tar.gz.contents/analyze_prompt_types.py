def per_prompt_type_depth_signal(df: pd.DataFrame) -> dict:
    """Per-prompt-type depth signal: Spearman correlations and within-type classifier F1."""
    results = {}
    for pt in PROMPT_TYPES:
        sub = df[df["prompt_type"] == pt].copy()
        if len(sub) < 50:
            results[pt] = {"status": "insufficient_data", "n": len(sub)}
            continue

        # Spearman correlation of each feature with depth
        correlations = {}
        for feat in FEATURES:
            rho, p = spearmanr(sub[feat], sub["depth"])
            correlations[feat] = {"rho": float(rho), "p": float(p)}

        # Within-type 5-fold CV classifier
        from sklearn.model_selection import StratifiedKFold
        skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)
        fold_f1s = []
        for train_idx, test_idx in skf.split(sub, sub["label"]):
            train_fold = sub.iloc[train_idx]
            test_fold = sub.iloc[test_idx]
            rng = np.random.RandomState(SEED)
            train_ds = downsample(train_fold, rng)
            clf = XGBClassifier(**XGB_PARAMS)
            clf.fit(train_ds[FEATURES].values, train_ds["label"].values)
            y_pred = clf.predict(test_fold[FEATURES].values)
            fold_f1s.append(float(f1_score(test_fold["label"].values, y_pred, average="macro")))

        results[pt] = dict(
            n=len(sub),
            depth_distribution=sub["depth"].value_counts().sort_index().to_dict(),
            spearman_correlations=correlations,
            cv5_macro_f1=dict(mean=float(np.mean(fold_f1s)),
                              std=float(np.std(fold_f1s)),
                              folds=fold_f1s),
        )
    return results


def leave_one_prompt_type_out(df: pd.DataFrame) -> dict:
    """Train on 2 prompt types, test on the held-out type."""
    results = {}
    all_y_test, all_y_pred = [], []
    for pt in PROMPT_TYPES:
        test_df = df[df["prompt_type"] == pt]
        train_df = df[df["prompt_type"] != pt]
        if len(test_df) < 10 or len(train_df) < 10:
            results[pt] = {"status": "insufficient_data"}
            continue
        res = train_eval_classifier(train_df, test_df)
        results[pt] = res
        all_y_test.append(test_df["label"].values)
        all_y_pred.append(
            XGBClassifier(**XGB_PARAMS).fit(
                downsample(train_df, np.random.RandomState(SEED))[FEATURES].values,
                downsample(train_df, np.random.RandomState(SEED))["label"].values
            ).predict(test_df[FEATURES].values)
        )
        ci = res["bootstrap_ci"]
        print(f"  LOPTO hold-out={pt:25s}  macro-F1={res['macro_f1']:.4f}  "
              f"95%CI=[{ci['ci_lo']:.4f}, {ci['ci_hi']:.4f}]")

    if all_y_test:
        combined_yt = np.concatenate(all_y_test)
        combined_yp = np.concatenate(all_y_pred)
        avg_f1 = float(f1_score(combined_yt, combined_yp, average="macro"))
        results["average_macro_f1"] = avg_f1
    return results


def depth_decay_comparison(df: pd.DataFrame) -> dict:
    """Compare how feature values decay/change with depth across prompt types."""
    results = {}
    for pt in PROMPT_TYPES:
        sub = df[df["prompt_type"] == pt]
        if len(sub) < 50:
            results[pt] = {"status": "insufficient_data"}
            continue

        decay = {}
        for feat in FEATURES:
            means_by_depth = sub.groupby("depth")[feat].mean()
            depths = np.array(means_by_depth.index, dtype=float)
            values = means_by_depth.values.astype(float)
            if len(depths) >= 2:
                slope = float(np.polyfit(depths, values, 1)[0])
                rho, p = spearmanr(depths, values)
            else:
                slope, rho, p = 0., 0., 1.
            decay[feat] = dict(
                means_by_depth={int(d): float(v) for d, v in zip(depths, values)},
                linear_slope=slope,
                spearman_rho=float(rho),
                spearman_p=float(p),
            )
        results[pt] = decay
    return results


def feature_distribution_comparison(df: pd.DataFrame) -> dict:
    """Compare feature distributions at depth 0 (shared seeds) vs deeper depths."""
    results = {}
    for feat in FEATURES:
        feat_res = {}
        for pt in PROMPT_TYPES:
            sub = df[df["prompt_type"] == pt]
            if len(sub) < 10:
                continue
            feat_res[pt] = dict(
                mean=float(sub[feat].mean()),
                std=float(sub[feat].std()),
                by_depth={int(d): float(v) for d, v in
                          sub.groupby("depth")[feat].mean().items()},
            )
        results[feat] = feat_res
    return results


