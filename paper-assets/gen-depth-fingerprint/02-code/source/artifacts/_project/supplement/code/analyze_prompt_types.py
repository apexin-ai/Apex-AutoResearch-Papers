"""
analyze_prompt_types.py — Prompt type comparison analysis

Compare depth signal strength across 3 prompt types (continuation, elaboration,
inspired_rewriting) generated by Pythia-2.8B on 1000 seeds x 5 depths.

Input:
  data/pythia-2.8b-{prompt_type}/generations.jsonl  (merged) or
  data/pythia-2.8b-{prompt_type}/generations_shard*.jsonl  (shards)
  Each line: {"id", "depth", "text", "seed_id", "token_count", "model", "prompt_type"}

Output:
  data/prompt_type_features.csv          — extracted features per sample
  data/prompt_type_results.json          — full evaluation results
  stdout: summary table

Dependencies: torch, transformers, numpy, pandas, xgboost, scipy, scikit-learn
Reference model: Pythia-410M (local snapshot)
"""

import argparse
import glob
import json
import os
import sys
from collections import Counter
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from scipy.stats import spearmanr
from sklearn.metrics import f1_score
from transformers import AutoModelForCausalLM, AutoTokenizer
from xgboost import XGBClassifier

SEED = 42
PROJECT_ROOT = Path(__file__).resolve().parent.parent

MODEL_SNAPSHOT = os.environ.get(
    "REF_MODEL_PATH",
    str(PROJECT_ROOT / "models" / "pythia-410m"),
)

PROMPT_TYPES = ["continuation", "elaboration", "inspired_rewriting"]

FEATURES = ["entropy_mean", "entropy_std", "entropy_min", "entropy_max",
            "tail_decay", "ttr", "hapax_ratio"]

CLASS_MAP = {0: 0, 1: 1, 2: 2, 3: 2, 4: 2}
CLASS_NAMES = ["gen-0", "gen-1", "gen-2+"]

XGB_PARAMS = dict(n_estimators=200, max_depth=6, learning_rate=0.1,
                  random_state=SEED, eval_metric="mlogloss",
                  use_label_encoder=False)


# ---------------------------------------------------------------------------
# Data loading
# ---------------------------------------------------------------------------

def find_data_files(prompt_type: str) -> list[str]:
    """Find generation files for a prompt type (merged or shards)."""
    base = PROJECT_ROOT / "data" / f"pythia-2.8b-{prompt_type}"
    merged = base / "generations.jsonl"
    if merged.exists():
        return [str(merged)]
    shards = sorted(glob.glob(str(base / "generations_shard*.jsonl")))
    return shards


def load_generations(prompt_type: str) -> list[dict]:
    files = find_data_files(prompt_type)
    if not files:
        print(f"  WARNING: no data files found for {prompt_type}")
        return []
    records = []
    for fp in files:
        with open(fp) as f:
            for line in f:
                line = line.strip()
                if line:
                    records.append(json.loads(line))
    print(f"  {prompt_type}: {len(records)} records from {len(files)} file(s)")
    return records


def load_all_data() -> pd.DataFrame:
    """Load all prompt types into a single DataFrame."""
    all_records = []
    for pt in PROMPT_TYPES:
        recs = load_generations(pt)
        for r in recs:
            r.setdefault("prompt_type", pt)
        all_records.extend(recs)
    if not all_records:
        print("ERROR: no data loaded")
        sys.exit(1)
    df = pd.DataFrame(all_records)
    df["label"] = df["depth"].map(CLASS_MAP)
    print(f"\nTotal: {len(df)} records, prompt types: {df['prompt_type'].value_counts().to_dict()}")
    return df


# ---------------------------------------------------------------------------
# Feature extraction (mirrors extract_features.py)
# ---------------------------------------------------------------------------

def load_model(device: str):
    print(f"Loading reference model from {MODEL_SNAPSHOT} on {device}")
    tokenizer = AutoTokenizer.from_pretrained(MODEL_SNAPSHOT, local_files_only=True)
    model = AutoModelForCausalLM.from_pretrained(
        MODEL_SNAPSHOT, local_files_only=True, torch_dtype=torch.float16,
    ).to(device).eval()
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    return tokenizer, model


@torch.no_grad()
def compute_entropy(text: str, tokenizer, model, device: str) -> dict:
    enc = tokenizer(text, return_tensors="pt", truncation=True, max_length=1024)
    input_ids = enc["input_ids"].to(device)
    if input_ids.shape[1] < 2:
        return {}
    logits = model(input_ids).logits[:, :-1, :]
    probs = torch.softmax(logits, dim=-1)
    log_probs = torch.log_softmax(logits, dim=-1)
    ent = -(probs * log_probs).sum(dim=-1).squeeze(0)
    ent_np = ent.float().cpu().numpy()
    sorted_lp = torch.gather(log_probs, 2, input_ids[:, 1:].unsqueeze(-1)).squeeze()
    sorted_lp = sorted_lp.float().cpu().numpy()
    n = len(sorted_lp)
    if n > 100:
        tail = sorted_lp[np.argsort(sorted_lp)[:max(1, n // 10)]]
        x = np.arange(len(tail), dtype=np.float64)
        if len(x) >= 2:
            slope = np.polyfit(x, tail, 1)[0]
        else:
            slope = 0.0
    else:
        slope = 0.0
    tokens = tokenizer.convert_ids_to_tokens(input_ids.squeeze().tolist())
    unique = set(tokens)
    ttr = len(unique) / len(tokens) if tokens else 0
    hapax = sum(1 for t in unique if tokens.count(t) == 1) / len(unique) if unique else 0
    return {
        "entropy_mean": float(ent_np.mean()),
        "entropy_std": float(ent_np.std()),
        "entropy_min": float(ent_np.min()),
        "entropy_max": float(ent_np.max()),
        "tail_decay": float(slope),
        "ttr": ttr,
        "hapax_ratio": hapax,
    }


def extract_all_features(df: pd.DataFrame, device: str, batch_size: int) -> pd.DataFrame:
    tokenizer, model = load_model(device)
    feat_rows = []
    for i, row in df.iterrows():
        feats = compute_entropy(row["text"], tokenizer, model, device)
        feat_rows.append(feats)
        if (i + 1) % 500 == 0:
            print(f"  Extracted {i + 1}/{len(df)}")
    feat_df = pd.DataFrame(feat_rows)
    for col in FEATURES:
        df[col] = feat_df[col].values
    return df


# ---------------------------------------------------------------------------
# Analysis functions
# ---------------------------------------------------------------------------

def per_prompt_type_depth_signal(df: pd.DataFrame) -> dict:
    results = {}
    for pt in PROMPT_TYPES:
        sub = df[df["prompt_type"] == pt]
        sig = {}
        for feat in FEATURES:
            rho, p = spearmanr(sub["depth"], sub[feat])
            sig[feat] = {"rho": round(float(rho), 4), "p": float(p)}
        results[pt] = {"spearman_correlations": sig, "n_samples": len(sub)}
        top3 = sorted(sig.items(), key=lambda x: abs(x[1]["rho"]), reverse=True)[:3]
        top_str = ", ".join(f"{f}={v['rho']:+.4f}" for f, v in top3)
        print(f"  {pt:25s}: {top_str}  (n={len(sub)})")
    return results


def leave_one_prompt_type_out(df: pd.DataFrame) -> dict:
    results = {}
    for held_out in PROMPT_TYPES:
        train_df = df[df["prompt_type"] != held_out]
        test_df = df[df["prompt_type"] == held_out]
        X_train, y_train = train_df[FEATURES].values, train_df["label"].values
        X_test, y_test = test_df[FEATURES].values, test_df["label"].values
        clf = XGBClassifier(**XGB_PARAMS)
        clf.fit(X_train, y_train)
        y_pred = clf.predict(X_test)
        f1 = f1_score(y_test, y_pred, average="macro")
        results[held_out] = {"macro_f1": round(float(f1), 4),
                             "n_train": len(train_df), "n_test": len(test_df)}
        print(f"  Held-out: {held_out:25s} macro-F1: {f1:.4f}")
    return results


def depth_decay_comparison(df: pd.DataFrame) -> dict:
    results = {}
    for pt in PROMPT_TYPES:
        sub = df[df["prompt_type"] == pt]
        decay = {}
        for feat in FEATURES:
            means = sub.groupby("depth")[feat].mean()
            depths = means.index.values.astype(float)
            vals = means.values
            if len(depths) >= 2:
                slope = np.polyfit(depths, vals, 1)[0]
            else:
                slope = 0.0
            decay[feat] = {"linear_slope": round(float(slope), 6)}
        results[pt] = decay
    return results


def feature_distribution_comparison(df: pd.DataFrame) -> dict:
    from scipy.stats import kruskal
    results = {}
    for feat in FEATURES:
        groups = [g[feat].values for _, g in df.groupby("prompt_type")]
        stat, p = kruskal(*groups)
        results[feat] = {"kruskal_H": round(float(stat), 4), "p": float(p)}
        sig = "***" if p < 0.001 else "**" if p < 0.01 else "*" if p < 0.05 else "ns"
        print(f"  {feat:15s}: H={stat:.2f}, p={p:.2e} {sig}")
    return results


def print_summary(results: dict):
    print("\n" + "=" * 80)
    print("SUMMARY")
    print("=" * 80)

    print("\n1. Per-Prompt-Type Spearman rho (top-3 |rho|)")
    sig = results.get("per_prompt_type_signal", {})
    for pt in PROMPT_TYPES:
        r = sig.get(pt, {})
        if "spearman_correlations" not in r:
            continue
        corrs = r["spearman_correlations"]
        top3 = sorted(corrs.items(), key=lambda x: abs(x[1]["rho"]), reverse=True)[:3]
        top_str = ", ".join(f"{f}={v['rho']:+.4f}" for f, v in top3)
        print(f"  {pt:25s}: {top_str}")

    print("\n2. Leave-One-Prompt-Type-Out macro-F1")
    lopto = results.get("leave_one_prompt_type_out", {})
    for pt in PROMPT_TYPES:
        r = lopto.get(pt, {})
        if "macro_f1" in r:
            print(f"  Held-out: {pt:25s} F1={r['macro_f1']:.4f}")

    print("\n3. Depth Decay (linear slope)")
    decay = results.get("depth_decay", {})
    header_feats = ["entropy_mean", "entropy_std", "tail_decay", "ttr"]
    print(f"{'Prompt Type':>25s}  " + "  ".join(f"{f:>14s}" for f in header_feats))
    print("-" * (25 + 2 + len(header_feats) * 16))
    for pt in PROMPT_TYPES:
        r = decay.get(pt, {})
        if isinstance(r, dict) and "status" not in r:
            vals = [f"{r[f]['linear_slope']:+14.6f}" for f in header_feats]
            print(f"{pt:>25s}  " + "  ".join(vals))

    print("\n4. Strongest Depth Correlations per Prompt Type (|rho| top-3)")
    for pt in PROMPT_TYPES:
        r = sig.get(pt, {})
        if "spearman_correlations" not in r:
            continue
        corrs = r["spearman_correlations"]
        sorted_feats = sorted(corrs.items(), key=lambda x: abs(x[1]["rho"]), reverse=True)[:3]
        top_str = ", ".join(f"{f}={v['rho']:+.4f}" for f, v in sorted_feats)
        print(f"  {pt:25s}: {top_str}")

    print("\n" + "=" * 80)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="Prompt type comparison analysis")
    parser.add_argument("--device", default="cuda:0", help="CUDA device")
    parser.add_argument("--batch-size", type=int, default=8, help="GPU batch size")
    parser.add_argument("--features-csv", default="data/prompt_type_features.csv",
                        help="Path to save/load features CSV")
    parser.add_argument("--output", default="data/prompt_type_results.json",
                        help="Output JSON path")
    parser.add_argument("--skip-extraction", action="store_true",
                        help="Skip feature extraction, load from --features-csv")
    parser.add_argument("--dry-run", action="store_true",
                        help="Process only first 50 records per prompt type")
    args = parser.parse_args()

    features_path = PROJECT_ROOT / args.features_csv
    output_path = PROJECT_ROOT / args.output

    # --- Load data ---
    print("Loading data...")
    df = load_all_data()

    if args.dry_run:
        df = df.groupby("prompt_type").head(50).reset_index(drop=True)
        print(f"[dry-run] Trimmed to {len(df)} records")

    # --- Feature extraction ---
    if args.skip_extraction and features_path.exists():
        print(f"\nLoading pre-extracted features from {features_path}")
        feat_df = pd.read_csv(features_path)
        for col in FEATURES:
            df[col] = feat_df[col].values
    else:
        print(f"\nExtracting features ({len(df)} texts)...")
        df = extract_all_features(df, args.device, args.batch_size)
        features_path.parent.mkdir(parents=True, exist_ok=True)
        df[["id", "depth", "seed_id", "prompt_type"] + FEATURES].to_csv(
            features_path, index=False)
        print(f"Features saved to {features_path}")

    # --- Analysis ---
    all_results = {}

    print("\n" + "=" * 60)
    print("1. Per-Prompt-Type Depth Signal")
    print("=" * 60)
    all_results["per_prompt_type_signal"] = per_prompt_type_depth_signal(df)

    print("\n" + "=" * 60)
    print("2. Leave-One-Prompt-Type-Out (LOPTO)")
    print("=" * 60)
    all_results["leave_one_prompt_type_out"] = leave_one_prompt_type_out(df)

    print("\n" + "=" * 60)
    print("3. Depth Decay Comparison")
    print("=" * 60)
    all_results["depth_decay"] = depth_decay_comparison(df)

    print("\n" + "=" * 60)
    print("4. Feature Distribution Comparison")
    print("=" * 60)
    all_results["feature_distributions"] = feature_distribution_comparison(df)

    # --- Output ---
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(all_results, f, indent=2, ensure_ascii=False)
    print(f"\nResults saved to {output_path}")

    print_summary(all_results)


if __name__ == "__main__":
    main()
