#!/usr/bin/env python3
"""
Fill 72B LaTeX macros from oracle_qwen72b_n500 experiment output.

Input:  seed_42.json (oracle experiment JSON with baseline/pruned results)
Output: artifacts/paper/72b_macros.tex (LaTeX \\renewcommand definitions)

Usage:
    python src/fill_72b_macros.py outputs/oracle_qwen72b_n500/seed_42.json
    python src/fill_72b_macros.py outputs/oracle_qwen72b_n500/seed_42.json --dry-run
"""

import argparse
import json
import math
import sys
from pathlib import Path


def mcnemar_exact_p(b, c):
    """Two-sided McNemar exact p-value using binomial test."""
    from scipy.stats import binomtest
    n = b + c
    if n == 0:
        return 1.0
    return binomtest(b, n, 0.5, alternative="two-sided").pvalue


def mcnemar_chi2_p(b, c):
    """McNemar chi-squared with continuity correction."""
    n = b + c
    if n == 0:
        return 1.0
    chi2 = (abs(b - c) - 1) ** 2 / n
    from scipy.stats import chi2 as chi2_dist
    return 1.0 - chi2_dist.cdf(chi2, df=1)


def paired_proportion_ci(b, c, n, z=1.96):
    """95% CI for difference of paired proportions (Wald interval on McNemar cells).

    b = pruned-only correct, c = baseline-only correct, n = total tasks.
    Returns (ci_low_pp, ci_high_pp) in percentage points.
    """
    delta = (b - c) / n
    if b + c == 0:
        return (0.0, 0.0)
    se = math.sqrt((b + c - (b - c) ** 2 / n)) / n
    return ((delta - z * se) * 100, (delta + z * se) * 100)


def main():
    parser = argparse.ArgumentParser(description="Fill 72B LaTeX macros from experiment JSON")
    parser.add_argument("json_path", type=Path, help="Path to seed_42.json")
    parser.add_argument("--output", type=Path, default=None,
                        help="Output .tex path (default: artifacts/paper/72b_macros.tex)")
    parser.add_argument("--dry-run", action="store_true", help="Print macros without writing")
    args = parser.parse_args()

    project_root = Path(__file__).resolve().parent.parent
    output_path = args.output or (project_root / "artifacts" / "paper" / "72b_macros.tex")

    data = json.loads(args.json_path.read_text())

    is_partial = "per_task" in data and "baseline" not in data

    if is_partial:
        print("[partial checkpoint mode]")
        per_task = data["per_task"]
        n_effective = data["total"]
        n_skipped = sum(1 for t in per_task if t.get("skipped"))
        baseline_correct = data["baseline_correct"]
        pruned_correct = data["oracle_correct"]
        baseline_acc = baseline_correct / n_effective * 100
        pruned_acc = pruned_correct / n_effective * 100
        delta_pp = pruned_acc - baseline_acc
        total_suppressed = data.get("total_suppressed", 0)
        total_rounds = data.get("total_agent_rounds", 1)
        supp_rate = total_suppressed / total_rounds * 100 if total_rounds else 0.0
        b = sum(1 for t in per_task if not t.get("skipped")
                and t.get("oracle_pruned_correct") and not t.get("baseline_correct"))
        c = sum(1 for t in per_task if not t.get("skipped")
                and t.get("baseline_correct") and not t.get("oracle_pruned_correct"))
        p_value = mcnemar_chi2_p(b, c)
    else:
        n_total = data["num_tasks"]
        n_skipped = data.get("num_skipped", 0)
        n_effective = data["baseline"]["total"]
        baseline_correct = data["baseline"]["correct"]
        pruned_correct = data["oracle_pruned"]["correct"]
        baseline_acc = baseline_correct / n_effective * 100
        pruned_acc = pruned_correct / n_effective * 100
        delta_pp = pruned_acc - baseline_acc
        supp_rate = data["oracle_pruned"]["suppression_rate"]
        b = data["mcnemar"]["b_oracle_only"]
        c = data["mcnemar"]["c_baseline_only"]
        p_from_json = data["mcnemar"]["p_value"]
        try:
            p_recomputed = mcnemar_chi2_p(b, c)
        except ImportError:
            p_recomputed = p_from_json
        if abs(p_from_json - p_recomputed) > 0.01:
            print(f"WARNING: p-value mismatch: JSON={p_from_json:.4f} vs recomputed={p_recomputed:.4f}")
        p_value = p_from_json

    ci_lo, ci_hi = paired_proportion_ci(b, c, n_effective)

    sign = "+" if delta_pp >= 0 else ""

    macros = (
        f"% === 72B N={n_effective} oracle results (auto-generated by fill_72b_macros.py) ===\n"
        f"% Source: {args.json_path}\n"
        f"% Guardrail: |Delta|={abs(delta_pp):.1f}pp, p={p_value:.3f}\n"
        f"% 95% CI: [{ci_lo:+.1f}, {ci_hi:+.1f}] pp\n"
        f"% Skipped: {n_skipped}, Effective N: {n_effective}\n"
        f"\\renewcommand{{\\qwenSevenTwoBBaseline}}{{{baseline_acc:.1f}}}\n"
        f"\\renewcommand{{\\qwenSevenTwoBPruned}}{{{pruned_acc:.1f}}}\n"
        f"\\renewcommand{{\\qwenSevenTwoBDelta}}{{{sign}{delta_pp:.1f}}}\n"
        f"\\renewcommand{{\\qwenSevenTwoBPvalue}}{{{p_value:.3f}}}\n"
        f"\\renewcommand{{\\qwenSevenTwoBSupp}}{{{supp_rate:.1f}}}\n"
        f"\\renewcommand{{\\qwenSevenTwoBN}}{{{n_effective}}}\n"
    )

    print("=" * 60)
    print(macros)
    print("=" * 60)
    print(f"Baseline: {baseline_correct}/{n_effective} = {baseline_acc:.1f}%")
    print(f"Pruned:   {pruned_correct}/{n_effective} = {pruned_acc:.1f}%")
    print(f"Delta:    {sign}{delta_pp:.1f} pp")
    print(f"95% CI:   [{ci_lo:+.1f}, {ci_hi:+.1f}] pp")
    print(f"McNemar:  p = {p_value:.4f} (b={b}, c={c})")
    print(f"Supp:     {supp_rate:.1f}%")
    print(f"Skipped:  {n_skipped}")
    print()

    # Guardrail
    if abs(delta_pp) <= 3.0 and p_value >= 0.1:
        print("SCENARIO A: |Delta| <= 3pp AND p >= 0.1")
        print("  -> Keep current framing (scale-invariant). Fill macros directly.")
    else:
        reasons = []
        if abs(delta_pp) > 3.0:
            reasons.append(f"|Delta|={abs(delta_pp):.1f}pp > 3pp")
        if p_value < 0.1:
            reasons.append(f"p={p_value:.3f} < 0.1")
        print(f"WARNING — SCENARIO B (CONTINGENCY-B): {', '.join(reasons)}")
        print("  -> Must activate CONTINGENCY-B narrative rewrite!")
        print("  -> Do NOT simply fill macros — reframe scale discussion first.")

    if args.dry_run:
        print("\n[dry-run] Not writing file.")
        return

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(macros)
    print(f"\nWritten to {output_path}")


if __name__ == "__main__":
    main()
